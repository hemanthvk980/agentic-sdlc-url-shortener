CREATE TABLE click_event (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    link_id       BIGINT NOT NULL REFERENCES link (id),
    clicked_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    click_date    DATE NOT NULL,
    referrer_host VARCHAR(255)
);

-- Stats queries filter by link and day; retention deletes by time.
CREATE INDEX ix_click_event_link_date ON click_event (link_id, click_date);
CREATE INDEX ix_click_event_clicked_at ON click_event (clicked_at);
